export function VendorIcon({
  name,
  provider,
  size = 16,
}: {
  name: string;
  provider?: string | null;
  size?: number;
}) {
  const vendor = resolveModelVendor(name, provider);
  const markSize = Math.max(10, Math.round(size * 0.72));
  return (
    <span
      className={`vendor-ico vendor-${vendor}`}
      title={vendorLabel(vendor)}
      aria-hidden
      style={{ width: size, height: size }}
    >
      <svg viewBox="0 0 24 24" width={markSize} height={markSize} fill="currentColor" aria-hidden>
        {marks[vendor]}
      </svg>
    </span>
  );
}

export function ModelLabel({
  name,
  provider,
  fallback,
  size = 16,
}: {
  name: string;
  provider?: string | null;
  fallback?: string;
  size?: number;
}) {
  const text = fallback ?? name;
  return (
    <span className="model-label">
      <VendorIcon name={name} provider={provider} size={size} />
      <span className="model-label-text">{text || "（未知）"}</span>
    </span>
  );
}
